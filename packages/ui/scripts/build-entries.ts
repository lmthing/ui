// Generates src/entry/{catalog,renderers,kit}.ts from the component folders. Output is gitignored.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath, URL } from "node:url";
import ts from "typescript";

const root = fileURLToPath(new URL("../", import.meta.url));
const entryDir = join(root, "src/entry");
const dataExports = ["meta", "props", "fallback", "examples", "probes"] as const;
const header = "// Generated by scripts/build-entries.ts. Do not edit.\n";

async function scan(folder: string): Promise<string[]> {
  const entries = await readdir(folder, { withFileTypes: true }).catch(() => []);
  const paths = await Promise.all(
    entries.map(async (entry) => {
      const path = join(folder, entry.name);
      if (entry.isDirectory()) return scan(path);
      return /^[A-Z][A-Za-z0-9]*\.tsx$/.test(entry.name) ? [path] : [];
    }),
  );
  return paths.flat().sort();
}

function exportedNames(file: string, source: string): string[] {
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  return ast.statements.flatMap((node) => {
    const exported =
      ts.canHaveModifiers(node) && ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
    if (!exported) return [];
    if (ts.isFunctionDeclaration(node)) return node.name ? [node.name.text] : [];
    if (ts.isVariableStatement(node))
      return node.declarationList.declarations.map((d) => d.name.getText(ast));
    return [];
  });
}

async function definitions() {
  const folders = ["components", "packs", "surfaces"].map((folder) => join(root, "src", folder));
  const files = (await Promise.all(folders.map(scan))).flat();
  return Promise.all(
    files.map(async (file) => {
      const source = await readFile(file, "utf8");
      const name = file.split("/").at(-1)!.replace(".tsx", "");
      const names = exportedNames(file, source);
      const draft = /status:\s*["']draft["']/.test(source);
      const missing = dataExports.filter((key) => !names.includes(key));
      if (!draft && !names.includes(name)) missing.push(name as never);
      if (missing.length) throw new Error(`${file} is missing exports: ${missing.join(", ")}`);
      const path = `./${relative(entryDir, file).replace(/\.tsx$/, "")}`;
      return { name, draft, path };
    }),
  );
}

export async function buildEntries() {
  const defs = await definitions();
  const ready = defs.filter((def) => !def.draft);
  const catalog = [
    header,
    `import { registryOf, type Definition, type RegistryOptions } from "../catalog";`,
    ...defs.map(({ name, path }) => `import * as ${name} from "${path}";`),
    `export * from "../catalog";`,
    "",
    "export const components = {",
    ...defs.map(
      ({ name }) => `  ${name}: { ${dataExports.map((key) => `${key}: ${name}.${key}`).join(", ")} },`,
    ),
    "} satisfies Record<string, Definition>;",
    "export type ComponentName = keyof typeof components;",
    "",
    "export function createRegistry(options: RegistryOptions = {}) {",
    "  return registryOf(components, options);",
    "}",
  ];
  const renderers = [
    header,
    ...ready.map(({ name, path }) => `import { ${name} } from "${path}";`),
    "",
    `export const renderers = { ${ready.map((def) => def.name).join(", ")} };`,
  ];
  const kit = [
    header,
    `import { createElement } from "react";`,
    `import { PhoneScreen as BasePhoneScreen, type PhoneScreenProps as BasePhoneScreenProps } from "../kit/screen/PhoneScreen";`,
    `import { components } from "./catalog";`,
    `import { renderers } from "./renderers";`,
    `export * from "../kit";`,
    `export { renderers };`,
    `export type PhoneScreenProps = Omit<BasePhoneScreenProps, "defs" | "renderers">;`,
    `export function PhoneScreen(props: PhoneScreenProps) {`,
    `  return createElement(BasePhoneScreen, { ...props, defs: components, renderers });`,
    `}`,
  ];
  await writeFile(join(entryDir, "catalog.ts"), `${catalog.join("\n")}\n`);
  await writeFile(join(entryDir, "renderers.ts"), `${renderers.join("\n")}\n`);
  await writeFile(join(entryDir, "kit.ts"), `${kit.join("\n")}\n`);
  console.log(`Entries: ${defs.length} definition(s), ${ready.length} renderer(s).`);
}

await buildEntries();
