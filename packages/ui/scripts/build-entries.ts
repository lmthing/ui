import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, URL } from "node:url";
import ts from "typescript";

const root = fileURLToPath(new URL("../", import.meta.url));
const exports = ["meta", "props", "fallback", "examples", "probes"] as const;

async function scan(folder: string): Promise<string[]> {
  const entries = await readdir(folder, { withFileTypes: true });
  const paths = await Promise.all(entries.map(async (entry) => {
    const path = join(folder, entry.name);
    return entry.isDirectory() ? scan(path) : entry.name.endsWith(".tsx") ? [path] : [];
  }));
  return paths.flat().sort();
}

async function definitions() {
  const files = (await Promise.all(["components", "packs", "surfaces"].map(
    (folder) => scan(join(root, "src", folder)),
  ))).flat();
  return Promise.all(files.map(async (file) => {
    const source = await readFile(file, "utf8");
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    const name = file.split("/").at(-1)!.replace(".tsx", "");
    const names = ast.statements.flatMap((node) => {
      if (ts.isFunctionDeclaration(node)) return [node.name?.text];
      if (ts.isVariableStatement(node)) return node.declarationList.declarations.map((d) => d.name.getText(ast));
      return [];
    });
    const draft = /status:\s*["']draft["']/.test(source);
    if (exports.some((key) => !names.includes(key)) || (!draft && !names.includes(name))) {
      throw new Error(`Incomplete component: ${file}`);
    }
    return { file, name, draft, folder: dirname(file) };
  }));
}

export async function buildEntries() {
  const defs = await definitions();
  const groups = new Map<string, typeof defs>();
  for (const def of defs) groups.set(def.folder, [...(groups.get(def.folder) ?? []), def]);
  for (const [folder, group] of groups) {
    const lines = group.flatMap(({ name, draft }) => [
      ...exports.map((key) => `export { ${key} as ${name}${key} } from "./${name}";`),
      ...(!draft ? [`export { ${name} } from "./${name}";`] : []),
    ]);
    await writeFile(join(folder, "index.ts"), `// Generated by build-entries.ts.\n${lines.join("\n")}\n`);
  }
  const imports = defs.map(({ name, folder }) =>
    `import { ${exports.map((key) => `${name}${key}`).join(", ")} } from "${relative(join(root, "src/entry"), folder)}";`,
  );
  const data = defs.map(({ name }) =>
    `  ${name}: { ${exports.map((key) => `${key}: ${name}${key}`).join(", ")} },`,
  );
  const header = "// Generated by build-entries.ts. Do not edit.\n";
  await writeFile(join(root, "src/entry/catalog.ts"), `${header}export * from "../catalog";\n${imports.join("\n")}\nexport const components = {\n${data.join("\n")}\n};\nexport function createRegistry() { return createCatalogRegistry(components); }\nimport { createCatalogRegistry } from "../catalog";\n`);
  const ready = defs.filter((def) => !def.draft);
  await writeFile(join(root, "src/entry/renderers.ts"), `${header}${ready.map(({ name, folder }) =>
    `import { ${name} } from "${relative(join(root, "src/entry"), folder)}";`).join("\n")}\nexport const renderers = { ${ready.map((def) => def.name).join(", ")} };\n`);
  await writeFile(join(root, "src/entry/kit.ts"), `${header}export * from "../kit";\nexport { renderers } from "./renderers";\n`);
  console.log(`Generated entries for ${defs.length} component(s), ${ready.length} renderer(s).`);
}

await buildEntries();
