import { readFile, writeFile } from "node:fs/promises";
import { URL } from "node:url";
import { accents, presets, themeName } from "../src/catalog";

export async function buildThemes() {
  const entries = presets.flatMap((preset) =>
    (["light", "dark"] as const).flatMap((mode) =>
      accents.map(
        (accent) =>
          `  ${themeName({ preset: preset.id, accent: accent.id, mode })}: ${JSON.stringify({
            ...preset.roles[mode],
            ...accent[mode],
          })},`,
      ),
    ),
  );
  const source = `// Generated by build-themes.ts. Do not edit.\nexport const kitThemes = {\n${entries.join("\n")}\n} as const;\n`;
  const target = new URL("../src/kit/tamagui/themes.generated.ts", import.meta.url);
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== source) throw new Error("Generated themes are stale");
  } else {
    await writeFile(target, source);
  }
  console.log(`${entries.length} themes ${process.argv.includes("--check") ? "checked" : "generated"}.`);
}

await buildThemes();
