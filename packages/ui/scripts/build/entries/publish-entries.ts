import { mkdir, mkdtemp, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { format, resolveConfig } from "prettier";

type Outputs = Record<string, string[]>;

async function pruneGroups(entry: string, folder: string, outputs: Outputs) {
  for (const group of await readdir(join(entry, folder), { withFileTypes: true })) {
    const path = `${folder}/${group.name}`;
    if (group.isDirectory() && /^group-\d+$/.test(group.name)) {
      if (!Object.hasOwn(outputs, `${path}/index.ts`)) {
        await rm(join(entry, path), { recursive: true, force: true });
        continue;
      }
      for (const file of await readdir(join(entry, path), { withFileTypes: true })) {
        const name = `${path}/${file.name}`;
        if (file.isFile() && file.name.endsWith(".ts") && !Object.hasOwn(outputs, name))
          await rm(join(entry, name), { force: true });
      }
    } else if (group.isFile() && /^group-\d+\.ts$/.test(group.name) && !Object.hasOwn(outputs, path)) {
      await rm(join(entry, path), { force: true });
    }
  }
}

function readExisting(file: string) {
  return readFile(file, "utf8").catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return undefined;
    throw error;
  });
}

export async function publishEntries(root: string, outputs: Outputs) {
  const options = await resolveConfig(join(root, "package.json"));
  const entry = join(root, "src/entry");
  let staging: string | undefined;
  try {
    // Publish leaves before their doors. Concurrent builds of the same sources never remove live paths.
    for (const [name, lines] of Object.entries(outputs)) {
      const file = join(entry, name);
      const source = `${lines.join("\n")}\n`;
      const text = name.endsWith(".ts")
        ? await format(`// Generated by scripts/build-entries.ts. Do not edit.\n${source}`, {
            ...options,
            parser: "typescript",
          })
        : source;
      if (text.trimEnd().split("\n").length > 200)
        throw new Error(`Generated entry exceeds 200 lines: ${file}`);
      if ((await readExisting(file)) === text) continue;
      staging ??= await mkdtemp(join(root, ".entries-"));
      const temp = join(staging, "entry.tmp");
      await mkdir(dirname(file), { recursive: true });
      await writeFile(temp, text);
      await rename(temp, file);
    }
    // Callers finish generation before reading. Prune only paths the new doors no longer reference.
    await pruneGroups(entry, "packs", outputs);
    await pruneGroups(entry, "views", outputs);
  } finally {
    if (staging) await rm(staging, { recursive: true, force: true });
  }
}
