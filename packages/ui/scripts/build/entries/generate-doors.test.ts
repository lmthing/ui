import { glob, mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { expect, it } from "vitest";
import { generateEntries } from "./index";

it("matches the former handwritten doors' exact value and type exports", async () => {
  const src = fileURLToPath(new URL("../../../src/", import.meta.url));
  const doors = (
    await Array.fromAsync(
      glob(["packs/*/{components,copy}/index.ts", "{catalog/copy,kit/base}/index.ts"], { cwd: src }),
    )
  ).sort();
  const paths = doors.map((door) => join(src, door));
  const leaves = await Array.fromAsync(
    glob(["packs/*/{components,copy}/**/*.{ts,tsx}", "{catalog/copy,kit/base}/**/*.{ts,tsx}"], {
      cwd: src,
      exclude: ["**/*.test.{ts,tsx}"],
    }),
  );
  // The export chain stays inside those folders; don't load view and runtime dependencies.
  const program = ts.createProgram(
    leaves.map((leaf) => join(src, leaf)),
    {
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      module: ts.ModuleKind.ESNext,
      jsx: ts.JsxEmit.ReactJSX,
      noLib: true,
      noResolve: true,
      types: [],
    },
  );
  const checker = program.getTypeChecker();
  const actual = paths.map((path, index) => {
    const source = program.getSourceFile(path)!;
    expect(source.text).toMatch(/^\/\/ Generated by /);
    const symbol = checker.getSymbolAtLocation(source)!;
    const names = checker.getExportsOfModule(symbol).map((member) => {
      const alias = member.flags & ts.SymbolFlags.Alias;
      const target = alias ? checker.getAliasedSymbol(member) : member;
      const typeOnly =
        !(target.flags & ts.SymbolFlags.Value) || (alias && checker.getTypeOnlyAliasDeclaration(member));
      return `${member.name}${typeOnly ? ":type" : ""}`;
    });
    return `${doors[index]} ${names.sort().join(" ")}`;
  });
  const expected = await readFile(new URL("./legacy-door-exports.txt", import.meta.url), "utf8");
  expect(actual).toEqual(expected.trimEnd().split("\n"));
});

it("regenerates sorted sibling exports without changing other doors", async () => {
  const root = await mkdtemp(resolve(".doors-test-"));
  const copy = "packs/booking/copy";
  const packDoor = 'export const example = "logic";\n';
  async function put(path: string, source: string) {
    const file = join(root, "src", path);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, source);
  }
  try {
    await put("packs/booking/index.ts", packDoor);
    await put(`${copy}/Zebra.ts`, "export const zebra = 1;");
    await put(`${copy}/ignored.test.ts`, "export const ignored = 1;");
    await put(`${copy}/helper/index.ts`, "export const helper = 1;");
    await put(`${copy}/Alpha.ts`, "export type Alpha = string;");
    await generateEntries(root);
    const body = async () =>
      (await readFile(join(root, "src", copy, "index.ts"), "utf8")).trim().split("\n").slice(1);
    expect(await body()).toEqual([
      'export * from "./Alpha";',
      'export * from "./Zebra";',
      'export * from "./helper";',
    ]);
    await rm(join(root, "src", copy, "Zebra.ts"));
    await generateEntries(root);
    expect(await body()).toEqual(['export * from "./Alpha";', 'export * from "./helper";']);
    expect(await readFile(join(root, "src/packs/booking/index.ts"), "utf8")).toBe(packDoor);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
